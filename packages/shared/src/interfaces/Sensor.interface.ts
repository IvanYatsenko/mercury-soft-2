/**
 * Типы датчиков температуры (термопар).
 * В печи Меркурий есть два датчика:
 * - Основной — у дальней стенки камеры
 * - Дополнительный — сверху камеры (для контроля температуры платы)
 */
export enum SensorType {
  /** Основной датчик (у дальней стенки) */
  PRIMARY = 'PRIMARY',
  /** Дополнительный датчик (сверху камеры) */
  SECONDARY = 'SECONDARY',
}

/**
 * Датчик температуры (термопара).
 * Используется для контроля температуры в рабочей камере.
 */
export interface Sensor {
  /** Уникальный идентификатор датчика */
  id: string;
  /** Название датчика */
  name: string;
  /** Тип датчика */
  type: SensorType;
  /** Текущая температура (°C) */
  currentTemperature: number;
  /** Максимальная температура, которую может измерять (°C) */
  maxTemperature: number;
  /** Активен ли датчик */
  isActive: boolean;
}
