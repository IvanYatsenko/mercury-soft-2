/**
 * Типы нагревательных элементов печи.
 * В печи Меркурий используется комбинированная система нагрева:
 * - ТЭНы (трубчатые электронагреватели)
 * - Инфракрасные лампы
 * - Вентиляторы (для конвекции)
 */
export enum HeaterType {
  /** Трубчатый электронагреватель */
  HEATING_ELEMENT = 'HEATING_ELEMENT',
  /** Инфракрасная лампа */
  INFRARED_LAMP = 'INFRARED_LAMP',
  /** Вентилятор конвекции */
  CONVECTION_FAN = 'CONVECTION_FAN',
  /** Вентилятор охлаждения */
  COOLING_FAN = 'COOLING_FAN',
}

/**
 * Нагревательный элемент печи.
 * Управляется программно через сенсорный экран.
 */
export interface Heater {
  /** Уникальный идентификатор нагревателя */
  id: string;
  /** Название нагревателя */
  name: string;
  /** Тип нагревателя */
  type: HeaterType;
  /** Включён ли нагреватель (true = зелёная иконка на экране) */
  isActive: boolean;
  /** Мощность (Вт) */
  power: number;
  /** Текущая температура (для ТЭНов) */
  temperature?: number;
}
