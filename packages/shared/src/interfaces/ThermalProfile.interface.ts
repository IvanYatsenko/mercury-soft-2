/**
 * Один этап термопрофиля.
 * Соответствует строке в редакторе профиля печи.
 */
export interface TemperatureStage {
  /** Длительность этапа в секундах */
  second: number;
  /** Целевая температура в конце этапа в градусах Цельсия */
  temperature: number;
}

/**
 * Параметры полки (платы) в упрощённом режиме.
 */
export interface ShelvesStage {
  /** Время, в течение которого удерживается температура (в секундах) */
  time: number;
  /** Температура полки (°C) */
  temperature: number;
}

/**
 * Модель термопрофиля для хранения в базе данных.
 * Это полноценная сущность, которую мы будем сохранять и загружать.
 */
export interface ThermalProfile {
  /** Уникальный идентификатор профиля */
  id: string;
  /** Человеческое название профиля */
  name: string;
  /** Список этапов, из которых состоит профиль */
  stages: TemperatureStage[];
  /** Режим редактирования: "easy" (упрощённый) или "manual" (детальный) */
  mode: 'easy' | 'manual';
  /** Использовать ли дополнительный внешний датчик температуры */
  useExternalSensor: boolean;
  /** Параметры полки (актуально для упрощённого режима) */
  shelves: ShelvesStage;
  /** Дата создания профиля */
  createdAt: Date;
  /** Дата последнего изменения профиля */
  updatedAt: Date;
}
