/**
 * Состояния, в которых может находиться печь.
 * Соответствуют реальным состояниям оборудования.
 */
export enum FurnaceStatus {
  /** Печь выключена или простаивает */
  IDLE = 'IDLE',
  /** Печь выполняет рабочий цикл */
  WORK = 'WORK',
  /** Печь занята (например, охлаждением или паузой) */
  BUSY = 'BUSY',
  /** Произошла ошибка */
  ERROR = 'ERROR',
}

/**
 * Типы ошибок, которые может генерировать печь.
 */
export enum FurnaceErrorType {
  /** Информационное сообщение, не ошибка */
  INFO = 'INFO',
  /**
   * Предупреждение. Система работает, но возникло отклонение
   * (например, открыта дверца). Система пытается скорректировать процесс.
   */
  WARNING = 'WARNING',
  /**
   * Критическая ситуация. Накопилось слишком много предупреждений,
   * или система не смогла скорректировать отклонение.
   * Процесс остановлен, требуется вмешательство оператора.
   */
  CRITICAL = 'CRITICAL',
  /**
   * Аварийная ситуация (перегрев, обрыв связи).
   * Печь недоступна. Требуется перезапуск устройства.
   */
  FAILURE = 'FAILURE',
}

/** Структура ошибки печи. */
export interface FurnaceError {
  type: FurnaceErrorType;
  code: number;
  message: string;
}

/** Модель печи для работы в системе. */
export interface Furnace {
  /** Уникальный лицензионный номер печи */
  licenseNumber: string;
  /** IP-адрес печи в локальной сети */
  ip: string;
  /** Тип/модель печи */
  model: 'Mercury-301' | 'Mercury-401';
  /** Версия установленного программного обеспечения */
  softwareVersion: string;
  /** Человекочитаемое имя (редактируемое) */
  name: string;
  /** Дополнительное описание (необязательно) */
  description?: string;
  /** Текущий статус */
  status: FurnaceStatus;
  /** Текущая температура в камере (°C) */
  temperature: number;
  /** ID текущего выполняемого профиля (если есть) */
  currentProfileId: string | null;
  /** Информация об ошибке (если статус ERROR) */
  error: FurnaceError | null;
}
